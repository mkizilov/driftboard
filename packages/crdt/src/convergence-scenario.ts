import { createManualClock, type Clock, type ManualClock } from './clock';
import { HybridLogicalClock } from './hlc';
import { replicaId, type ReplicaId } from './replica-id';

/**
 * Generic convergence harness, part 1: runs one scenario against any operation-based CRDT.
 * This file has no test-framework imports; `convergence.ts` adds the fast-check generators.
 */

/** Scenarios use between `MIN_REPLICAS` and `MAX_REPLICAS` replicas. */
export const MIN_REPLICAS = 3;
export const MAX_REPLICAS = 5;
const INITIAL_TIME_MS = 1000;
const REFERENCE_REPLICA = replicaId('ref');

export interface ReplicaContext {
  readonly replicaId: ReplicaId;
  /** The replica's physical clock. The harness moves it between steps, even backwards. */
  readonly physicalClock: Clock;
  /** A hybrid clock driven by `physicalClock`, for CRDTs that need timestamps from the harness. */
  readonly clock: HybridLogicalClock;
}

/**
 * Describes a CRDT to the harness. `S` is the replica state, `Op` an operation, `Intent` a random
 * description of what a user does (generated by fast-check) that `prepare` turns into operations.
 *
 * `apply` may mutate its state and return the same object (the text sequence does). Such a spec
 * must make `apply` idempotent, because the harness applies every operation `prepare` returned
 * once more (`prepare` may already have applied them), and it cannot provide `merge`, which needs
 * states that stay unchanged after being recorded.
 */
export interface ConvergenceSpec<S, Op, Intent> {
  readonly name: string;
  /**
   * Fresh, empty state for a replica. A state that keeps its own clock should read
   * `ctx.physicalClock`, so that the harness's clock jumps reach it.
   */
  readonly create: (replica: ReplicaId, ctx: ReplicaContext) => S;
  /**
   * Prepare phase: build the operations for an intent from the replica's current state, in the
   * order they must be applied (later ones may depend on earlier ones). Empty = nothing to do.
   */
  readonly prepare: (state: S, intent: Intent, ctx: ReplicaContext) => readonly Op[];
  /** Effect phase: apply an operation (local or remote) and return the new state. */
  readonly apply: (state: S, op: Op) => S;
  /**
   * Canonical, JSON-serialisable view of the *whole* state (not just the visible value), with every
   * collection in a deterministic order. Two replicas converged iff their snapshots serialise equally.
   */
  readonly snapshot: (state: S) => unknown;
  /** Optional state-based merge, checked against replaying the union of both sides' operations. */
  readonly merge?: (a: S, b: S) => S;
  /** Optional hook run before a remote operation is applied, e.g. to feed the HLC. */
  readonly observe?: (ctx: ReplicaContext, op: Op) => void;
  /** Set if applying an operation twice must change nothing; enables redelivery steps. */
  readonly idempotentApply?: boolean;
}

export type Step<Intent> =
  | {
      readonly kind: 'local';
      readonly replica: number;
      readonly intent: Intent;
      readonly clockDelta: number;
    }
  | { readonly kind: 'deliver'; readonly replica: number; readonly pick: number }
  | { readonly kind: 'redeliver'; readonly replica: number; readonly pick: number };

export interface Scenario<Intent> {
  /** Number of replicas, `MIN_REPLICAS` to `MAX_REPLICAS`. Step replica indices wrap around it. */
  readonly replicas: number;
  readonly steps: readonly Step<Intent>[];
  /** Choices used to pick the delivery order while draining the remaining operations. */
  readonly flushPicks: readonly number[];
  /** Triples of recorded states (indices wrap) to check the state merge on. */
  readonly mergePicks: readonly (readonly [number, number, number])[];
}

export interface ScenarioStats {
  ops: number;
  /** Pairs of operations where neither causally precedes the other. */
  concurrentPairs: number;
  redeliveries: number;
  mergeChecks: number;
}

interface LoggedOp<Op> {
  readonly op: Op;
  /** Indices of every operation the origin replica had applied when it created this one. */
  readonly deps: ReadonlySet<number>;
}

interface RecordedState<S> {
  readonly state: S;
  readonly applied: ReadonlySet<number>;
}

function at<T>(items: readonly T[], index: number): T {
  const item = items[index];
  if (item === undefined) throw new RangeError(`index ${index} out of range (${items.length})`);
  return item;
}

function pickFrom<T>(items: readonly T[], pick: number): T {
  return at(items, pick % items.length);
}

/** Compares two serialised snapshots. */
function assertSame(
  spec: string,
  actual: string | undefined,
  expected: string | undefined,
  message: string,
): void {
  if (actual !== expected) {
    throw new Error(`${spec}: ${message}\n  actual:   ${actual}\n  expected: ${expected}`);
  }
}

/**
 * Runs `scenario`: 3 to 5 replicas make local operations and receive each other's operations in
 * random but causally valid orders (an operation is delivered only after everything its origin
 * had applied when creating it). Afterwards everything is delivered and it throws unless:
 *  - all replicas have the same snapshot, equal to a reference replica that applied the operations
 *    in creation order;
 *  - redelivering an operation changes nothing (if `idempotentApply`);
 *  - `merge` of any recorded states is commutative, associative, idempotent and equals replaying
 *    the union of their operations (if `merge` is given).
 */
export function runScenario<S, Op, Intent>(
  spec: ConvergenceSpec<S, Op, Intent>,
  scenario: Scenario<Intent>,
): ScenarioStats {
  const count = scenario.replicas;
  if (!Number.isInteger(count) || count < MIN_REPLICAS || count > MAX_REPLICAS) {
    throw new RangeError(`replicas must be ${MIN_REPLICAS}-${MAX_REPLICAS}, got ${count}`);
  }
  const makeContext = (id: ReplicaId, physicalClock: ManualClock): ReplicaContext => ({
    replicaId: id,
    physicalClock,
    clock: new HybridLogicalClock({
      replicaId: id,
      physicalClock,
      maxDriftMs: Number.MAX_SAFE_INTEGER,
    }),
  });
  const ids = Array.from({ length: count }, (_, i) => replicaId(`r${i}`));
  const physical = ids.map(() => createManualClock(INITIAL_TIME_MS));
  const contexts = ids.map((id, i) => makeContext(id, at(physical, i)));
  const states: S[] = ids.map((id, i) => spec.create(id, at(contexts, i)));
  const applied = ids.map(() => new Set<number>());
  const log: LoggedOp<Op>[] = [];
  const history: RecordedState<S>[] = states.map((state) => ({
    state,
    applied: new Set<number>(),
  }));
  const stats: ScenarioStats = { ops: 0, concurrentPairs: 0, redeliveries: 0, mergeChecks: 0 };
  const snap = (state: S): string | undefined => JSON.stringify(spec.snapshot(state));

  const record = (r: number): void => {
    history.push({ state: at(states, r), applied: new Set(at(applied, r)) });
  };

  const deliverable = (r: number): number[] => {
    const have = at(applied, r);
    const ready: number[] = [];
    log.forEach((entry, index) => {
      if (!have.has(index) && [...entry.deps].every((dep) => have.has(dep))) ready.push(index);
    });
    return ready;
  };

  const deliver = (r: number, index: number): void => {
    const { op } = at(log, index);
    spec.observe?.(at(contexts, r), op);
    states[r] = spec.apply(at(states, r), op);
    at(applied, r).add(index);
    record(r);
  };

  for (const step of scenario.steps) {
    const r = step.replica % count;
    if (step.kind === 'local') {
      const clock = at(physical, r);
      clock.set(Math.max(0, clock.now() + step.clockDelta));
      for (const op of spec.prepare(at(states, r), step.intent, at(contexts, r))) {
        const index = log.length;
        log.push({ op, deps: new Set(at(applied, r)) });
        states[r] = spec.apply(at(states, r), op);
        at(applied, r).add(index);
        record(r);
      }
    } else if (step.kind === 'deliver') {
      const ready = deliverable(r);
      if (ready.length > 0) deliver(r, pickFrom(ready, step.pick));
    } else if (spec.idempotentApply === true) {
      const have = [...at(applied, r)];
      if (have.length === 0) continue;
      const before = at(states, r);
      const expected = snap(before); // taken first: `apply` may mutate `before`
      const after = spec.apply(before, at(log, pickFrom(have, step.pick)).op);
      assertSame(
        spec.name,
        snap(after),
        expected,
        `redelivering an applied operation changed the state of replica r${r}`,
      );
      states[r] = after;
      stats.redeliveries += 1;
    }
  }

  // Drain: deliver everything still pending, in an order chosen by the scenario.
  for (let round = 0; ; round += 1) {
    const pending = ids.flatMap((_, r) => deliverable(r).map((index) => [r, index] as const));
    if (pending.length === 0) break;
    const { flushPicks } = scenario;
    const pick = flushPicks.length === 0 ? 0 : at(flushPicks, round % flushPicks.length);
    const [r, index] = pickFrom(pending, pick);
    deliver(r, index);
  }

  const replay = (indices: ReadonlySet<number>): S => {
    const context = makeContext(REFERENCE_REPLICA, createManualClock(INITIAL_TIME_MS));
    let state = spec.create(REFERENCE_REPLICA, context);
    log.forEach((entry, index) => {
      if (indices.has(index)) state = spec.apply(state, entry.op);
    });
    return state;
  };

  const reference = snap(replay(new Set(log.keys())));
  states.forEach((state, r) => {
    const message = `replica r${r} diverged from the reference replica`;
    assertSame(spec.name, snap(state), reference, message);
  });

  stats.ops = log.length;
  for (let j = 0; j < log.length; j += 1) {
    for (let i = 0; i < j; i += 1) {
      if (!at(log, j).deps.has(i)) stats.concurrentPairs += 1;
    }
  }

  const { merge } = spec;
  if (merge !== undefined) {
    const union = (...parts: ReadonlySet<number>[]): Set<number> =>
      new Set(parts.flatMap((part) => [...part]));
    const name = spec.name;
    for (const [x, y, z] of scenario.mergePicks) {
      const s = pickFrom(history, x);
      const t = pickFrom(history, y);
      const u = pickFrom(history, z);
      const expected = snap(replay(union(s.applied, t.applied)));
      const merged = merge(s.state, t.state);
      assertSame(
        name,
        snap(merged),
        expected,
        'merge(a, b) differs from replaying the union of their operations',
      );
      assertSame(name, snap(merge(t.state, s.state)), expected, 'merge is not commutative');
      assertSame(name, snap(merge(s.state, s.state)), snap(s.state), 'merge is not idempotent');
      const left = merge(merged, u.state);
      const right = merge(s.state, merge(t.state, u.state));
      assertSame(name, snap(left), snap(right), 'merge is not associative');
      assertSame(
        name,
        snap(left),
        snap(replay(union(s.applied, t.applied, u.applied))),
        'merge of three states differs from replaying the union of their operations',
      );
      stats.mergeChecks += 1;
    }
    const [first, ...rest] = states;
    if (first === undefined) throw new RangeError('no replicas');
    assertSame(
      name,
      snap(rest.reduce(merge, first)),
      reference,
      'merging all final replica states differs from the reference replica',
    );
  }

  return stats;
}
